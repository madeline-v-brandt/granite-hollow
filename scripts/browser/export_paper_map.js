// Exports the paper trail map (paper.js) as a static SVG for the landing page's
// background: site/game/paper-map.svg. The landing page can't afford to build the
// park's scene (a second or more) just to draw it, so rerun this after changing
// the paper map or the park's layout:   node scripts/browser/export_paper_map.js
// The climbing areas, "you are here" and the view box are left out: the landing
// page shows the park, not a climber's knowledge of it.
const fs = require("fs");
const { open, ready, sleep, GAME_DIR } = require("./lib");
(async () => {
  const { b, p, errs, url } = await open();
  await p.goto(url); await p.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await p.goto(url, { waitUntil: "load" }); await p.waitForSelector("[data-str]");
  await p.evaluate(() => { const s = () => document.querySelectorAll("[data-str]"); s()[0].click(); s()[6].click(); document.querySelector("#cc-go").click(); });
  await ready(p); await sleep(500);
  await p.evaluate(() => document.querySelector(".modal [data-paper]").click()); await sleep(1500);
  const svg = await p.evaluate(() => {
    const s = document.querySelector("#paper-root svg.paper-svg").cloneNode(true);
    for (const sel of [".pp-areas", ".pp-view", ".pp-me"]) s.querySelectorAll(sel).forEach(g => g.remove());
    s.removeAttribute("style");
    s.setAttribute("xmlns", "http://www.w3.org/2000/svg");
    s.setAttribute("class", "paper-svg landing-svg");
    // Its own ids, so it can't stand in for the trail map's patterns in the game.
    return s.outerHTML.replace(/(id="|url\(#)pp-/g, "$1lp-");
  });
  const out = GAME_DIR + "paper-map.svg";
  fs.writeFileSync(out, "<!-- Generated by scripts/browser/export_paper_map.js from paper.js. Don't edit by hand. -->\n" + svg + "\n");
  console.log("wrote", out, (svg.length / 1024).toFixed(0), "KB", "| page errors:", errs.length ? errs : "none");
  await b.close();
})();
